-- Additive storage; no existing production data is changed. Test access is enforced by the API.
CREATE TABLE advent_test_clock (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    offset_seconds BIGINT
);
INSERT INTO advent_test_clock (id, offset_seconds) VALUES (1, NULL);
CREATE TABLE advent_test_clock_advances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    offset_seconds BIGINT NOT NULL
);
CREATE INDEX advent_test_clock_advances_received ON advent_test_clock_advances(received_at);

CREATE TABLE advent_test_member_state (
    user_id UUID PRIMARY KEY REFERENCES users(id),
    correct_streak INTEGER NOT NULL DEFAULT 0 CHECK (correct_streak >= 0)
);
CREATE TABLE advent_test_answers (
    user_id UUID NOT NULL REFERENCES users(id),
    quiz_day INTEGER NOT NULL CHECK (quiz_day BETWEEN 1 AND 24),
    choice INTEGER NOT NULL CHECK (choice BETWEEN 0 AND 2),
    correct_choice INTEGER NOT NULL CHECK (correct_choice BETWEEN 0 AND 2),
    response_points INTEGER NOT NULL,
    participation_points INTEGER NOT NULL,
    bonus_points INTEGER NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reveal_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, quiz_day)
);

-- A reservation makes a delayed confirmation revocable before a retry.
CREATE TABLE advent_test_attempts (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id),
    quiz_day INTEGER NOT NULL CHECK (quiz_day BETWEEN 1 AND 24),
    cancelled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX advent_test_attempts_member_day ON advent_test_attempts(user_id, quiz_day);

CREATE TABLE advent_test_generations (
    user_id UUID NOT NULL REFERENCES users(id),
    quiz_day INTEGER NOT NULL CHECK (quiz_day BETWEEN 1 AND 24),
    generation UUID NOT NULL,
    PRIMARY KEY (user_id, quiz_day)
);
